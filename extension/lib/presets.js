export const PRESET_GROUPS = [...new Set(PRESETS.map((p) => p.group))];

export function getPreset(id) {
  return PRESETS.find((p) => p.id === id) || null;
}

/** 把预设套用到现有条目上（保留 id / 名称，除非名称为空） */
export function applyPreset(preset, current = {}) {
  if (!preset) return current;
  return {
    ...current,
    name: current.name || preset.name,
    url: preset.url,
    method: preset.method,
    contentType: preset.contentType,
    headers: preset.headers || '',
    template: preset.template,
    mdToHtml: preset.contentType.includes('html') ? Boolean(current.mdToHtml) : false,
  };
}
